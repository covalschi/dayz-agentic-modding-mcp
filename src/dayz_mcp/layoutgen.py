class LayoutGenError(ValueError):
    """A description the generator refuses: the file, the node and why."""

    def __init__(self, message: str, file: str = "", node: str = ""):
        super().__init__(message)
        self.message = message
        self.file = file
        self.node = node

    def __str__(self) -> str:
        where = " ".join(p for p in (self.file, self.node) if p)
        return f"{where}: {self.message}" if where else self.message


def fmt(value: float) -> str:
    """A number the way vanilla layouts write it: integers bare, floats to 3 places."""
    if isinstance(value, bool):
        raise TypeError("a bool is not a layout number")
    value = float(value)
    if value.is_integer():
        return str(int(value))
    return f"{value:.3f}".rstrip("0").rstrip(".")


def _is_number(value) -> bool:
    return isinstance(value, (int, float)) and not isinstance(value, bool)


@dataclass
class Tokens:
    """`ui/tokens.json`: the numbers, colours and fonts written once."""

    color: dict[str, list[float]] = field(default_factory=dict)
    font: dict[str, dict] = field(default_factory=dict)
    space: dict[str, float] = field(default_factory=dict)
    size: dict[str, float] = field(default_factory=dict)
    device: dict = field(default_factory=dict)
    file: str = "ui/tokens.json"

    @classmethod
    def from_text(cls, text: str, file: str = "ui/tokens.json") -> "Tokens":
        try:
            data = json.loads(text)
        except json.JSONDecodeError as exc:
            raise LayoutGenError(f"tokens do not parse: {exc}", file) from None
        if not isinstance(data, dict):
            raise LayoutGenError("tokens must be a JSON object", file)
        t = cls(file=file)
        for name, rgba in dict(data.get("color") or {}).items():
            good = (isinstance(rgba, list) and len(rgba) == 4
                    and all(_is_number(v) and 0 <= v <= 1 for v in rgba))
            if not good:
                raise LayoutGenError(f"color.{name} must be four numbers 0..1", file)
            t.color[name] = [float(v) for v in rgba]
        for name, spec in dict(data.get("font") or {}).items():
            good = (isinstance(spec, dict) and _is_number(spec.get("size"))
                    and isinstance(spec.get("face", FONT_FACE_DEFAULT), str)
                    and isinstance(spec.get("fixed", False), bool))
            if not good:
                raise LayoutGenError(f'font.{name} must be {{"face": str, "size": number, "fixed": bool}}', file)
            t.font[name] = {"face": spec.get("face", FONT_FACE_DEFAULT),
                            "size": float(spec["size"]), "fixed": bool(spec.get("fixed", False))}
        for group in ("space", "size"):
            for name, value in dict(data.get(group) or {}).items():
                if not _is_number(value):
                    raise LayoutGenError(f"{group}.{name} must be a number", file)
                getattr(t, group)[name] = float(value)
        t.device = dict(data.get("device") or {})
        return t

    def number(self, value, file: str, node: str, what: str = "size") -> float:
        """A number, or a `$space.<name>` / `$size.<name>` reference."""
        if isinstance(value, bool):
            raise LayoutGenError(f"{what} must be a number, not a bool", file, node)
        if _is_number(value):
            return float(value)
        if isinstance(value, str) and value.startswith("$"):
            group, _, name = value[1:].partition(".")
            table = {"space": self.space, "size": self.size}.get(group)
            if table is None or name not in table:
                raise LayoutGenError(f"unknown token {value!r} for {what}", file, node)
            return table[name]
        raise LayoutGenError(f"{what} must be a number or a $space/$size token, got {value!r}", file, node)

    def pair(self, value, file: str, node: str, what: str = "size") -> tuple[float, float]:
        """`[w, h]` of numbers or tokens, or `$device.<name>` naming a two-number token."""
        if isinstance(value, str) and value.startswith("$device."):
            got = self.device.get(value[len("$device."):])
            if not (isinstance(got, list) and len(got) == 2 and all(_is_number(v) for v in got)):
                raise LayoutGenError(f"{value!r} is not a [w, h] device token", file, node)
            return float(got[0]), float(got[1])
        if isinstance(value, list) and len(value) == 2:
            return (self.number(value[0], file, node, what + "[0]"),
                    self.number(value[1], file, node, what + "[1]"))
        raise LayoutGenError(f"{what} must be [w, h] or a $device token, got {value!r}", file, node)

    def color_of(self, value, file: str, node: str) -> tuple[list[float], bool]:
        """`(rgba, from_token)`: `$name` looks the colour up; a literal list passes and is reported."""
        if isinstance(value, str) and value.startswith("$"):
            name = value[1:]
            if name.startswith("color."):
                name = name[len("color."):]
            if name not in self.color:
                raise LayoutGenError(f"unknown color token {value!r}", file, node)
            return list(self.color[name]), True
        if isinstance(value, list) and len(value) == 4 and all(_is_number(v) for v in value):
            return [float(v) for v in value], False
        raise LayoutGenError(f"color must be a $token or four numbers, got {value!r}", file, node)

    def font_of(self, value, file: str, node: str) -> tuple[dict, bool]:
        """`(font, from_token)`: a token name (`header`, `$font.header`) or a literal spec."""
        if isinstance(value, str):
            name = value[1:] if value.startswith("$") else value
            if name.startswith("font."):
                name = name[len("font."):]
            if name in self.font:
                return dict(self.font[name]), True
            raise LayoutGenError(f"unknown font token {value!r}", file, node)
        if isinstance(value, dict) and _is_number(value.get("size")):
            return {"face": value.get("face", FONT_FACE_DEFAULT), "size": float(value["size"]),
                    "fixed": bool(value.get("fixed", False))}, False
        raise LayoutGenError(f'font must be a token name or {{"face", "size"}}, got {value!r}', file, node)


@dataclass
class W:
    """One widget to write: class, name, ordered properties, children."""

    cls: str
    name: str
    props: list[tuple[str, str]] = field(default_factory=list)
    children: list["W"] = field(default_factory=list)
    comment: str = ""

    def set(self, key: str, value: str) -> "W":
        for i, (k, _v) in enumerate(self.props):
            if k == key:
                self.props[i] = (key, value)
                return self
        self.props.append((key, value))
        return self


def quoted(text: str) -> str:
    return '"' + text + '"'


def key(name: str) -> str:
    """A property key as the engine wants it: quoted when it has spaces."""
    return quoted(name) if " " in name else name


def color_prop(rgba: list[float]) -> str:
    return " ".join(fmt(v) for v in rgba)


def render(w: W, indent: int = 0) -> str:
    pad = " " * indent
    lines = [f"{pad}// {c}".rstrip() for c in w.comment.splitlines()]
    lines.append(f"{pad}{w.cls} {w.name} {{")
    lines += [f"{pad} {k} {v}" for k, v in w.props]
    if w.children:
        lines.append(f"{pad} {{")
        lines += [render(c, indent + 2) for c in w.children]
        lines.append(f"{pad} }}")
    lines.append(f"{pad}}}")
    return "\n".join(lines)


ANCHORS = {"right": ("right_ref", None), "bottom": (None, "bottom_ref"),
           "center": ("center_ref", "center_ref"), "bottom-right": ("right_ref", "bottom_ref")}


def place(w: W, x: float, y: float, width: float, height: float,
          hexact: bool = True, vexact: bool = True, anchor: str = "") -> W:
    """Position and size, exact unless told otherwise; an anchor moves the reference edge."""
    ha, va = ANCHORS.get(anchor, (None, None))
    if ha:
        w.set("halign", ha)
    if va:
        w.set("valign", va)
    w.set("position", f"{fmt(x)} {fmt(y)}")
    w.set("size", f"{fmt(width)} {fmt(height)}")
    w.set("hexactpos", "1")
    w.set("vexactpos", "1")
    w.set("hexactsize", "1" if hexact else "0")
    w.set("vexactsize", "1" if vexact else "0")
    return w


@dataclass
class Box:
    """What a child may occupy: the parent's inner size and where that inner
    area starts (`ox`/`oy`, a frame's inset -- positions are written relative
    to the parent WIDGET, so a child at the inner origin sits at `ox oy`).
    `w`/`h` None = not known here (an engine container decides); `prop_w` =
    the parent's width is the engine's to decide (a row under a scrollbar),
    so a full-width child is `size 1`."""

    w: float | None
    h: float | None
    prop_w: bool = False
    ox: float = 0.0
    oy: float = 0.0
    #: children are laid out by the engine: every child must be one widget
    engine: bool = False


@dataclass
class Ctx:
    tokens: Tokens
    file: str
    layout_dir: str
    notes: list[str] = field(default_factory=list)
    files: dict[str, str] = field(default_factory=dict)
    names: set[str] = field(default_factory=set)
    gaps: int = 0
    chain: list[int] = field(default_factory=list)

    def claim(self, name, path: str) -> str:
        if not isinstance(name, str) or not name:
            raise LayoutGenError("a widget needs a name (a non-empty string)", self.file, path)
        if name in self.names:
            raise LayoutGenError(f"duplicate widget name {name!r} in this file", self.file, path)
        self.names.add(name)
        return name

    def gap_name(self, path: str) -> str:
        self.gaps += 1
        return self.claim(f"Gap{self.gaps}", path)

    def fresh(self) -> "Ctx":
        """A context for another FILE of the same build: names start over,
        notes and files are shared."""
        return Ctx(self.tokens, self.file, self.layout_dir, self.notes, self.files)

    def note(self, path: str, text: str) -> None:
        self.notes.append(f"{self.file} {path}: {text}")


@dataclass
class Emitted:
    """What one description makes: `files` maps a project-relative path
    (`<Mod>/gui/layouts/<name>.layout`) to its text."""

    files: dict[str, str]
    notes: list[str]


