def build_layout(desc, tokens: Tokens, file: str = "", layout_dir: str = "") -> Emitted:
    """One page description -> its .layout text plus the row files it owns.

    `file` is the description's project-relative path (named in errors and
    in the GENERATED header); `layout_dir` is where the files go
    (`MyMod/gui/layouts`), so the keys of `files` are project-relative.
    """
    if not isinstance(desc, dict):
        raise LayoutGenError("a description is a JSON object", file)
    name = desc.get("layout")
    if not isinstance(name, str) or not name:
        raise LayoutGenError('"layout" (the file name without .layout) is required', file)
    extra = sorted(set(desc) - {"layout", "note", "root", "body"})
    if extra:
        raise LayoutGenError(f"a description does not take {extra}", file)
    if "root" not in desc:
        raise LayoutGenError('"root" is required', file)
    ctx = Ctx(tokens=tokens, file=file, layout_dir=layout_dir)
    kind, attrs = _unpack(desc["root"], file, "root")
    if kind not in ROOT_KINDS:
        raise LayoutGenError(f"root must be a frame or a panel, not {kind}", file, "root")
    if "size" not in attrs or attrs["size"] == "fill":
        raise LayoutGenError("root needs an exact size [w, h]", file, "root")
    width, height = tokens.pair(attrs["size"], file, "root")
    root = W("FrameWidgetClass" if kind == "frame" else "PanelWidgetClass",
             ctx.claim(attrs.get("name", name), "root"), comment=str(attrs.get("note", "")))
    root.set("visible", "0" if attrs.get("hidden") else "1")
    place(root, 0, 0, width, height)
    if kind == "panel":
        _color(root, attrs, ctx, "root", "$screen")
        root.set("style", PANEL_STYLE)
    if "priority" in attrs:
        root.set("priority", fmt(_priority(attrs, ctx, "root", 0)))
    inset = tokens.number(attrs.get("inset", 0), file, "root", "inset")
    inner = Box(width - 2 * inset, height - 2 * inset, ox=inset, oy=inset)
    children = list(attrs.get("children", []))
    if "body" in desc:
        children.append(desc["body"])
    ctx.chain.append(_priority(attrs, ctx, "root", 0))
    for i, child in enumerate(children):
        root.children += emit(child, ctx, inner, f"root.{i}", i, on_page=True)
    head = [GENERATED_MARK + file + " -- edit the source, not this file."]
    head += [f"// {line}" for line in str(desc.get("note", "")).splitlines()]
    text = "\n".join(head) + "\n" + render(root) + "\n"
    target = f"{layout_dir}/{name}.layout" if layout_dir else f"{name}.layout"
    files = {target: text}
    files.update(ctx.files)
    return Emitted(files, ctx.notes)


@dataclass
class BuildReport:
    """`written` = files that differed from what is on disk (and were written
    when `write` was on); `files` = every generated path -> text; `sources`
    = generated path -> the description it came from."""

    written: list[str] = field(default_factory=list)
    unchanged: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)
    files: dict[str, str] = field(default_factory=dict)
    sources: dict[str, str] = field(default_factory=dict)


def build_project(root, mods: list[str], sources: dict[str, str], mod: str = "",
                  write: bool = True) -> BuildReport:
    """Generate every description under `<root>/ui/<Mod>/` for `mods`.

    Generation completes for every file before anything is written, so a bad
    description leaves the disk exactly as it was. Files are written with LF
    endings, compared after normalising CRLF, so a checkout on either setting
    reads as unchanged.
    """
    root = Path(root)
    report = BuildReport()
    wanted = [m for m in mods if not mod or m == mod]
    dirs = [(m, root / UI_DIR / m) for m in wanted if (root / UI_DIR / m).is_dir()]
    if not dirs:
        return report
    tokens_rel = f"{UI_DIR}/{TOKENS_FILE}"
    tokens_path = root / UI_DIR / TOKENS_FILE
    if not tokens_path.is_file():
        raise LayoutGenError(f"{tokens_rel} is missing but {UI_DIR}/<Mod>/ exists", tokens_rel)
    tokens = Tokens.from_text(tokens_path.read_text(encoding="utf-8"), tokens_rel)
    for m, ui_dir in dirs:
        for path in sorted(ui_dir.glob("*.json")):
            rel = path.relative_to(root).as_posix()
            try:
                desc = json.loads(path.read_text(encoding="utf-8"))
            except json.JSONDecodeError as exc:
                raise LayoutGenError(f"does not parse: {exc}", rel) from None
            emitted = build_layout(desc, tokens, rel, f"{m}/{LAYOUT_DIR}")
            report.notes += emitted.notes
            for target, text in emitted.files.items():
                if target in report.files:
                    raise LayoutGenError(f"{target} is generated by two descriptions "
                                         f"({report.sources[target]} and {rel})", rel)
                report.files[target] = text
                report.sources[target] = rel
    for target, text in report.files.items():
        head, _, rest = target.partition("/")
        out = resolve_mod_dir(root, sources, head) / rest
        current = out.read_text(encoding="utf-8") if out.is_file() else None
        if current is not None and current.replace("\r\n", "\n") == text:
            report.unchanged.append(target)
            continue
        report.written.append(target)
        if write:
            out.parent.mkdir(parents=True, exist_ok=True)
            with out.open("w", encoding="utf-8", newline="\n") as fh:
                fh.write(text)
    return report


def main(argv=None) -> int:
    """`python -m dayz_mcp.layoutgen <project root> [mod]` -- the tool without the server."""
    from .profile import load_profile
    args = list(sys.argv[1:] if argv is None else argv)
    if not args:
        print("usage: python -m dayz_mcp.layoutgen <project root> [mod]")
        return 2
    loaded = load_profile(args[0])
    if not loaded.ok:
        print(loaded.error)
        return 1
    prof = loaded.data
    mod = args[1] if len(args) > 1 else ""
    if mod and mod not in prof.build.mods:
        print(f"{mod!r} is not a mod of this project; it declares: {', '.join(prof.build.mods)}")
        return 1
    try:
        report = build_project(prof.root, prof.build.mods, prof.build.sources, mod)
    except LayoutGenError as exc:
        print(f"refused: {exc}")
        return 1
    for p in report.written:
        print("wrote", p)
    for p in report.unchanged:
        print("unchanged", p)
    for n in report.notes:
        print("note", n)
    return 0


if __name__ == "__main__":
    sys.exit(main())
