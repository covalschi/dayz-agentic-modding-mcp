    fill = W("PanelWidgetClass", ctx.claim(name + "Fill", path))
    fill.set("visible", "1").set("ignorepointer", "1")
    place(fill, 1, 1, width - 2, height - 2)
    rgba, _ = ctx.tokens.color_of("$panel", ctx.file, path)
