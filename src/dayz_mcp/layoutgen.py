def _unpack(desc, file: str, path: str) -> tuple[str, dict]:
    if not isinstance(desc, dict) or len(desc) != 1:
        raise LayoutGenError("a node is an object with exactly one primitive key", file, path)
    (kind, attrs), = desc.items()
    if kind not in ALLOWED:
        raise LayoutGenError(f"unknown primitive {kind!r}; known: {', '.join(sorted(ALLOWED))}", file, path)
    if not isinstance(attrs, dict):
        raise LayoutGenError(f"{kind} must hold an object of attributes", file, path)
    extra = sorted(set(attrs) - ALLOWED[kind])
    if extra:
        raise LayoutGenError(f"{kind} does not take {extra}", file, path)
    return kind, attrs


def _priority(attrs: dict, ctx: Ctx, path: str, index: int) -> int:
    if "priority" not in attrs:
        return index
    return int(ctx.tokens.number(attrs["priority"], ctx.file, path, "priority"))


def _text_value(attrs: dict, ctx: Ctx, path: str) -> str:
    text = str(attrs.get("text", ""))
    if '"' in text:
        raise LayoutGenError("a quote inside text hangs the engine's layout parser", ctx.file, path)
    return text


def _dim(attrs: dict, which: str, ctx: Ctx, path: str, avail: float | None, default,
         allow_auto: bool = False):
    """One of w/h: a number, a token, "fill" (= `avail`), "auto" (a label's
    width) or `default`. `size: [w, h]` / `size: "fill"` stands for both."""
    value = attrs.get(which, default)
    if "size" in attrs:
        if "w" in attrs or "h" in attrs:
            raise LayoutGenError("size and w/h on one node -- use one", ctx.file, path)
        size = attrs["size"]
        if size == "fill":
            value = "fill"
        else:
            pair = ctx.tokens.pair(size, ctx.file, path)
            value = pair[0 if which == "w" else 1]
    if value is None:
        raise LayoutGenError(f"{which} is required here", ctx.file, path)
    if value == "fill":
        if avail is None:
            raise LayoutGenError(f"{which}: fill needs an exact ancestor to fill", ctx.file, path)
        return float(avail)
    if value == "auto":
        if not allow_auto:
            raise LayoutGenError("auto is only a label's width", ctx.file, path)
        return "auto"
    return ctx.tokens.number(value, ctx.file, path, which)


def _avail(side: float | None, inset: float) -> float | None:
    """How much of a box a child `inset` units in can fill (from the left or
    top for a plain child, from the edge it hangs off for an anchored one)."""
    if side is None:
        return None
    return side - inset


def _size_leaf(attrs: dict, ctx: Ctx, box: Box, path: str, x: float, y: float, forced: tuple,
               anchor: str, default_h, allow_auto: bool = False, exact_only: bool = False) -> tuple:
    """The (width, height, hexactsize, vexactsize) of one leaf.

    Two shortcuts stand in for arithmetic the engine does better, and
    `exact_only` (a container that must know its own numbers: vbox, grid,
    button, field, list) turns both off:

    * `size: "fill"` at an uninset origin is the parent's whole box, written
      `size 1 1` proportional -- no number to go stale when the parent moves;
    * an undeclared width inside a PROPORTIONAL parent (`box.prop_w`: a list
      row, whose width the engine sets from the scroll minus its bar) is
      `size 1 h`, hexactsize 0, for the same reason.

    Otherwise the size is exact: what the node declares, or the remainder of
    the box from where the node sits (`_avail`). `forced` is the axis a
    vbox/hbox has already decided, and it wins over both the declaration and
    the shortcuts. A label's `w: "auto"` returns width 0 -- the engine sizes
    it from its own text.
    """
    inset_x = x - box.ox
    inset_y = y - box.oy
    full = (attrs.get("size") == "fill" and "w" not in attrs and "h" not in attrs
            and x == 0 and y == 0 and box.ox == 0 and box.oy == 0
            and not anchor and forced == (None, None) and not exact_only)
    if full:
        return 1.0, 1.0, False, False
    w = forced[0] if forced[0] is not None else _dim(attrs, "w", ctx, path, _avail(box.w, inset_x), "fill", allow_auto)
    h = forced[1] if forced[1] is not None else _dim(attrs, "h", ctx, path, _avail(box.h, inset_y), default_h)
    hexact = True
    declared_w = "w" in attrs or "size" in attrs or forced[0] is not None
    if w != "auto" and box.prop_w and inset_x == 0 and not anchor and not declared_w and not exact_only:
        w, hexact = 1.0, False
    if w == "auto":
        return 0.0, h, True, True
    return w, h, hexact, True


def _common_leaf(cls: str, attrs: dict, ctx: Ctx, path: str, ignore: bool = True) -> W:
    w = W(cls, ctx.claim(attrs.get("name", ""), path), comment=str(attrs.get("note", "")))
    w.set("visible", "0" if attrs.get("hidden") else "1")
    if ignore:
        w.set("ignorepointer", "1")
    return w


def _color(w: W, attrs: dict, ctx: Ctx, path: str, default: str, attr: str = "color") -> W:
    """Read `attrs[attr]` (a `$token` or a literal) and write it as `color`
    on the widget. `attr` differs from `"color"` only for `bar`, whose one
    node carries two colours (`track`/`fill`) -- each read and noted the
    same way every other primitive's single `color` is."""
    rgba, from_token = ctx.tokens.color_of(attrs.get(attr, default), ctx.file, path)
    if not from_token:
        ctx.note(path, f"{attr} given as a literal -- use a $color token")
    return w.set("color", color_prop(rgba))


def _text_font(w: W, attrs: dict, ctx: Ctx, path: str, default: str) -> dict:
    font, from_token = ctx.tokens.font_of(attrs.get("font", default), ctx.file, path)
    if not from_token:
        ctx.note(path, "font given as a literal -- use a $font token")
    w.set("text", quoted(_text_value(attrs, ctx, path)))
    w.set("font", quoted(font["face"]))
    w.set(key("exact text"), "1")
    if not font["fixed"]:
        w.set(key("exact text size"), fmt(font["size"]))
    return font


def _children(attrs: dict, ctx: Ctx, box: Box, path: str) -> list[W]:
    out: list[W] = []
    for i, child in enumerate(attrs.get("children", [])):
        out += emit(child, ctx, box, f"{path}.{i}", i)
    return out


def emit(desc, ctx: Ctx, box: Box, path: str, index: int, placed: tuple | None = None,
         on_page: bool = False) -> list[W]:
    """One description node -> the widgets it stands for (a nameless
    vbox/hbox returns its children flattened, everything else one widget).

    `placed` = (x, y, w, h) decided by a vbox/hbox (w or h None = as the
    node declares); without it the node places itself with `at` (default
    0 0, offset by the box's inset) and `anchor`. `on_page` marks a direct
    child of a frame/panel page root, where a visible `at` is noted: pages
    are built with containers, not coordinates. False for a button root's
    children -- a button root is a fixed-size compound control, not a page.
    """
    kind, attrs = _unpack(desc, ctx.file, path)
    anchor = attrs.get("anchor", "")
    if anchor and anchor not in ANCHORS:
        raise LayoutGenError(f"unknown anchor {anchor!r}; one of {sorted(ANCHORS)}", ctx.file, path)
    if placed is None:
        ax, ay = ctx.tokens.pair(attrs.get("at", [0, 0]), ctx.file, path, "at")
        x = ax if anchor in ("center", "bottom-center") else ax + box.ox
        y = ay if anchor == "center" else ay + box.oy
        forced = (None, None)
        if on_page and "at" in attrs and not attrs.get("hidden"):
            ctx.note(path, "`at` on a page child -- build the page with vbox/hbox")
    else:
        if "at" in attrs:
            raise LayoutGenError(f"{kind}: `at` is not allowed under a vbox/hbox -- the container places it", ctx.file, path)
        # An anchor is refused for the same reason `at` is, and it is the
        # worse of the two: it does not move the widget, it changes what the
        # coordinate the container computed MEANS (`bottom_ref` reads a
        # top-down offset as a bottom-up one), so the child lands far away
        # and the siblings do not follow.
        if anchor:
            raise LayoutGenError(f"{kind}: `anchor` is not allowed under a vbox/hbox -- the container places it", ctx.file, path)
        x, y, fw, fh = placed
        forced = (fw, fh)
    builder = BUILDERS.get(kind)
    if builder is None:
        raise LayoutGenError(f"{kind} is not implemented", ctx.file, path)
    priority = _priority(attrs, ctx, path, index)
    ctx.chain.append(priority)
    try:
        return builder(attrs, ctx, box, path, x, y, forced, anchor, priority)
    finally:
        ctx.chain.pop()


def _b_frame(attrs, ctx, box, path, x, y, forced, anchor, priority) -> list[W]:
    w = _common_leaf("FrameWidgetClass", attrs, ctx, path, ignore=False)
    width, height, hx, vx = _size_leaf(attrs, ctx, box, path, x, y, forced, anchor, None)
    place(w, x, y, width, height, hx, vx, anchor)
    w.set("priority", fmt(priority))
    inset = ctx.tokens.number(attrs.get("inset", 0), ctx.file, path, "inset")
    inner_w = _inset_extent(width, hx, box.w, inset, "width", ctx, path)
    inner_h = _inset_extent(height, vx, box.h, inset, "height", ctx, path)
    inner = Box(inner_w, inner_h, prop_w=not hx and not inset, ox=inset, oy=inset)
    w.children = _children(attrs, ctx, inner, path)
    return [w]


def _inset_extent(size: float, exact: bool, box_size: float | None, inset: float,
                  axis: str, ctx: Ctx, path: str) -> float | None:
    """One axis of the room a panel's or frame's children have inside its
    own `inset`.

    Exact (`size` is a real number -- this node's own hexactsize/vexactsize)
    is `size - 2 * inset`, same arithmetic as a frame's inner box. Proportional
    (the "full" shortcut: this node's own `size` is 1.0, not a usable number)
    instead needs what the node actually renders as -- `box_size`, the box IT
    was handed, which is a real number whenever the nearest ancestor that
    fixed it is exact (a frame/vbox of known size) even though this node's
    own line stays proportional. Without an inset there is nothing to
    subtract, so an unresolved `box_size` (still `None`, e.g. under a screen
    root) passes through unchanged, exactly as before; WITH one, subtracting
    from an unknown `box_size` would hand a fill child the un-reduced box and
    it would overflow past this node's true edge by `inset` -- refused
    instead of silently drawn wrong.
    """
    if exact:
        return size - 2 * inset
    if not inset:
        return box_size
    if box_size is None:
        raise LayoutGenError(f"a proportional panel or frame with an inset needs a known {axis} -- "
                             "give it w/h or drop the inset", ctx.file, path)
    return box_size - 2 * inset


def _b_panel(attrs, ctx, box, path, x, y, forced, anchor, priority) -> list[W]:
    w = _common_leaf("PanelWidgetClass", attrs, ctx, path, ignore=not attrs.get("click"))
    width, height, hx, vx = _size_leaf(attrs, ctx, box, path, x, y, forced, anchor, None)
    place(w, x, y, width, height, hx, vx, anchor)
    _color(w, attrs, ctx, path, "$panel")
    w.set("priority", fmt(priority)).set("style", PANEL_STYLE)
    out = []
    if attrs.get("edge"):
        if not (hx and vx):
            raise LayoutGenError("edge needs an exact size", ctx.file, path)
        edge = W("PanelWidgetClass", ctx.claim(w.name + "Edge", path))
        edge.set("visible", "0" if attrs.get("hidden") else "1").set("ignorepointer", "1")
        # A border one unit outside the panel on every side. `right_ref` and
        # `bottom_ref` measure INTO the parent from that edge, so a position
        # one unit smaller still moves the border outwards there, exactly as
        # it does for an unanchored top-left one. `center_ref` measures from
        # the middle: growing by 2 is the whole of it, and the -1 would push
        # the border off-centre, leaving a 2-unit border on two sides and
        # none on the other two (measured 2026-09-04).
        ha, va = ANCHORS.get(anchor, (None, None))
        ex = x if ha == "center_ref" else x - 1
        ey = y if va == "center_ref" else y - 1
        place(edge, ex, ey, width + 2, height + 2, anchor=anchor)
        rgba, _ = ctx.tokens.color_of("$edge", ctx.file, path)
        edge.set("color", color_prop(rgba)).set("priority", fmt(priority)).set("style", PANEL_STYLE)
        out.append(edge)
    inset = ctx.tokens.number(attrs.get("inset", 0), ctx.file, path, "inset")
    inner_w = _inset_extent(width, hx, box.w, inset, "width", ctx, path)
    inner_h = _inset_extent(height, vx, box.h, inset, "height", ctx, path)
    inner = Box(inner_w, inner_h, prop_w=not hx and not inset, ox=inset, oy=inset)
    w.children = _children(attrs, ctx, inner, path)
    return out + [w]


